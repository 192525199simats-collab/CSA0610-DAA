SMALL_N = 100_000
LARGE_N = 1_000_000
OPERATIONS_PER_SECOND = 10
NIGHTLY_WINDOW_SECONDS = 10 * 60

def execution_time(operations):
    """Convert basic operations into seconds."""
    return operations / OPERATIONS_PER_SECOND

def check_nightly_window(operations):
    """Check whether processing fits into 10 minutes."""
    seconds = execution_time(operations)
    return seconds <= NIGHTLY_WINDOW_SECONDS

def format_time(seconds):
    if seconds < 60:
        return f"{seconds:.2f} seconds"
    if seconds < 3600:
        return f"{seconds / 60:.2f} minutes"
    if seconds < 86400:
        return f"{seconds / 3600:.2f} hours"
    return f"{seconds / 86400:.2f} days"


