def m2_audit_count(n):
    """
    i starts at 1 and doubles each iteration.
    The inner loop performs i Audit operations.
    Total = 1 + 2 + 4 + ... for powers of 2 strictly less than n.
    """
    total = 0
    i = 1

    while i < n:
        total += i
        i *= 2

    return total

def analyze_m2():
    print("\nM2: API RATE LIMITER")

