# DESIGN AND ANALYSIS OF ALGORITHMS - ASSIGNMENT 1
# Student Record Search System
# Algorithms: Linear Search, Recursive Binary Search, Hash Search

import time
import csv
import random

# --------------------------------------------------
# 1. LINEAR SEARCH (ITERATIVE)
# --------------------------------------------------

def linear_search(records, target):
    comparisons = 0

    for i, value in enumerate(records):
        comparisons += 1

        if value == target:
            return i, comparisons

    return -1, comparisons


# --------------------------------------------------
# 2. BINARY SEARCH (RECURSIVE)
# --------------------------------------------------

def binary_search(records, target, low, high):
    if low > high:
        return -1, 0

    mid = (low + high) // 2
    comparisons = 1

    if records[mid] == target:
        return mid, comparisons

    comparisons += 1

    if target < records[mid]:
        index, count = binary_search(
            records, target, low, mid - 1
        )
    else:
        index, count = binary_search(
            records, target, mid + 1, high
        )

    return index, comparisons + count


# --------------------------------------------------
# 3. HASH TABLE SEARCH
# --------------------------------------------------

def hash_search(record_set, target):
    start = time.perf_counter()
    found = target in record_set
    elapsed = time.perf_counter() - start

    return found, elapsed


# --------------------------------------------------
# 4. EXPERIMENTAL TESTING
# --------------------------------------------------

dataset_sizes = [1000, 10000, 100000, 1000000]
results = []

print("=" * 90)
print("STUDENT RECORD SEARCH ALGORITHM PERFORMANCE")
print("=" * 90)

for n in dataset_sizes:
    print(f"\nDataset size: {n:,}")

    # Generate unique registration numbers
    records = list(range(100001, 100001 + n))

    # Use the last record to test linear-search worst case
    target = records[-1]

    # ---------------- LINEAR SEARCH ----------------
    start = time.perf_counter()
    linear_index, linear_comparisons = linear_search(
        records, target
    )
    linear_time = time.perf_counter() - start

    assert linear_index == n - 1

    # ---------------- BINARY SEARCH ----------------
    # Shuffle records to measure sorting preprocessing
    shuffled_records = records.copy()
    random.Random(42).shuffle(shuffled_records)

    start = time.perf_counter()
    sorted_records = sorted(shuffled_records)
    sorting_time = time.perf_counter() - start

    start = time.perf_counter()
    binary_index, binary_comparisons = binary_search(
        sorted_records, target, 0, n - 1
    )
    binary_time = time.perf_counter() - start

    assert binary_index == n - 1

    # ---------------- HASH SEARCH ----------------
    start = time.perf_counter()
    record_set = set(records)
    hash_build_time = time.perf_counter() - start

    hash_found, hash_time = hash_search(record_set, target)

    assert hash_found is True
    assert (target + n) not in record_set

    # ---------------- RECORD RESULTS ----------------
    results.append({
        "Dataset_Size": n,
        "Linear_Time_Seconds": linear_time,
        "Linear_Comparisons": linear_comparisons,
        "Sorting_Time_Seconds": sorting_time,
        "Binary_Search_Time_Seconds": binary_time,
        "Binary_Comparisons": binary_comparisons,
        "Hash_Build_Time_Seconds": hash_build_time,
        "Hash_Search_Time_Seconds": hash_time
    })

    print(f"Linear Search Time       : {linear_time:.8f} seconds")
    print(f"Linear Comparisons       : {linear_comparisons}")

    print(f"Sorting Preprocessing    : {sorting_time:.8f} seconds")
    print(f"Binary Search Time       : {binary_time:.8f} seconds")
    print(f"Binary Comparisons       : {binary_comparisons}")

    print(f"Hash Construction Time   : {hash_build_time:.8f} seconds")
    print(f"Hash Search Time         : {hash_time:.8f} seconds")

