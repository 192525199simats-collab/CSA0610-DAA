def brute_force_convex_hull(points):
    points = list(dict.fromkeys(points))
    n = len(points)

    if n <= 2:
        return points

    boundary = set()

    for i in range(n):
        for j in range(i + 1, n):
            ax, ay = points[i]
            bx, by = points[j]

            positive = False
            negative = False

            for k in range(n):
                if k == i or k == j:
                    continue

                px, py = points[k]

                cross = (
                    (bx - ax) * (py - ay)
                    - (by - ay) * (px - ax)
                )

                if cross > 0:
                    positive = True
                elif cross < 0:
                    negative = True

            # A supporting line has all points on one side.
            if not (positive and negative):
                boundary.add(points[i])
                boundary.add(points[j])

    if len(boundary) <= 2:
        return list(boundary)

    # Arrange boundary points around their centroid.
    cx = sum(p[0] for p in boundary) / len(boundary)
    cy = sum(p[1] for p in boundary) / len(boundary)

    import math
    hull = sorted(
        boundary,
        key=lambda p: math.atan2(p[1] - cy, p[0] - cx)
    )

    return hull


def plot_hull(points, hull, title):
    plt.figure(figsize=(6, 5))

    plt.scatter(
        [p[0] for p in points],
        [p[1] for p in points],
        label="All points"
    )

    if hull:
        closed = hull + [hull[0]]
        plt.plot(
            [p[0] for p in closed],
            [p[1] for p in closed],
            marker="o",
            label="Convex hull"
        )

    plt.title(title)
    plt.xlabel("X coordinate")
    plt.ylabel("Y coordinate")
    plt.grid(True)
    plt.legend()
    plt.axis("equal")
    plt.show()


