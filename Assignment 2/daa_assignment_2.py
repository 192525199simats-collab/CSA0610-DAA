import math
import time


def closest_pair_brute_force(points):
    n = len(points)

    if n < 2:
        return None, 0, 0

    min_distance = float("inf")
    closest_pair = None
    pairs_examined = 0
    distance_calculations = 0

    start = time.perf_counter()

    for i in range(n - 1):
        for j in range(i + 1, n):
            pairs_examined += 1

            x1, y1 = points[i]
            x2, y2 = points[j]

            distance = math.sqrt(
                (x2 - x1) ** 2 + (y2 - y1) ** 2
            )
            distance_calculations += 1

            if distance < min_distance:
                min_distance = distance
                closest_pair = (points[i], points[j])

    elapsed = time.perf_counter() - start

    return closest_pair, min_distance, pairs_examined, distance_calculations, elapsed


