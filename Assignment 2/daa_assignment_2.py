def closest_pair_divide_conquer(points):
    points = list(points)

    if len(points) < 2:
        return None, 0

    points.sort(key=lambda p: p[0])
    distance_checks = [0]

    def distance(a, b):
        distance_checks[0] += 1
        return math.hypot(a[0] - b[0], a[1] - b[1])

    def solve(px):
        n = len(px)

        if n <= 3:
            best = float("inf")
            pair = None

            for i in range(n):
                for j in range(i + 1, n):
                    d = distance(px[i], px[j])
                    if d < best:
                        best = d
                        pair = (px[i], px[j])

            return best, pair

        mid = n // 2
        left = px[:mid]
        right = px[mid:]
        dividing_x = px[mid][0]

        dl, pair_l = solve(left)
        dr, pair_r = solve(right)

        if dl <= dr:
            best, pair = dl, pair_l
        else:
            best, pair = dr, pair_r

        strip = [
            p for p in px
            if abs(p[0] - dividing_x) < best
        ]
        strip.sort(key=lambda p: p[1])

        for i in range(len(strip)):
            j = i + 1

            while (
                j < len(strip)
                and strip[j][1] - strip[i][1] < best
            ):
                d = distance(strip[i], strip[j])

                if d < best:
                    best = d
                    pair = (strip[i], strip[j])

                j += 1

        return best, pair

    min_distance, pair = solve(points)

    return (pair, min_distance), distance_checks[0]


