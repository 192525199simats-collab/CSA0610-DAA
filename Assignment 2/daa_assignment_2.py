def selection_sort(arr):
    a = arr.copy()
    comparisons = 0
    swaps = 0

    for i in range(len(a) - 1):
        min_index = i

        for j in range(i + 1, len(a)):
            comparisons += 1
            if a[j] < a[min_index]:
                min_index = j

        if min_index != i:
            a[i], a[min_index] = a[min_index], a[i]
            swaps += 1

    return a, comparisons, swaps


def bubble_sort(arr):
    a = arr.copy()
    comparisons = 0
    swaps = 0

    for i in range(len(a) - 1):
        swapped = False

        for j in range(len(a) - 1 - i):
            comparisons += 1

            if a[j] > a[j + 1]:
                a[j], a[j + 1] = a[j + 1], a[j]
                swaps += 1
                swapped = True

        if not swapped:
            break

    return a, comparisons, swaps


def insertion_sort(arr):
    a = arr.copy()
    comparisons = 0
    movements = 0

    for i in range(1, len(a)):
        key = a[i]
        j = i - 1

        while j >= 0:
            comparisons += 1

            if a[j] > key:
                a[j + 1] = a[j]
                movements += 1
                j -= 1
            else:
                break

        a[j + 1] = key
        movements += 1

    return a, comparisons, movements


