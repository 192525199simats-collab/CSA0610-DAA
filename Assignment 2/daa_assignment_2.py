def exhaustive_package_search(weights, values, capacity):
    n = len(weights)
    best_value = 0
    best_weight = 0
    best_packages = []
    combinations_checked = 0

    # Examine every possible subset, including the empty subset.
    for mask in range(1 << n):
        total_weight = 0
        total_value = 0
        selected = []

        for i in range(n):
            if mask & (1 << i):
                total_weight += weights[i]
                total_value += values[i]
                selected.append(i)

        combinations_checked += 1

        if total_weight <= capacity and total_value > best_value:
            best_value = total_value
            best_weight = total_weight
            best_packages = selected

    return best_packages, best_weight, best_value, combinations_checked


