def brute_force_string_match(text, pattern):
    comparisons = 0
    n = len(text)
    m = len(pattern)

    if m == 0:
        return 0, comparisons

    for i in range(n - m + 1):
        j = 0

        while j < m:
            comparisons += 1

            if text[i + j] != pattern[j]:
                break

            j += 1

        if j == m:
            return i, comparisons

    return -1, comparisons


